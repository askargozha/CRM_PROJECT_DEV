"""
Быстрая, полностью бесплатная проверка "похоже ли это вообще на
жалобу по связи/интернету" — по ключевым словам, без единого
обращения к ИИ. Нужна для фильтрации обращений из внешней CRM (там
общие категории на все темы, не только связь) — чтобы явно
нерелевантные сообщения (про дороги, мусор, коммунальные услуги и
т.п.) отсеивались сразу, ещё до того как обращение вообще попадёт
в нашу систему.

Это НЕ замена ИИ-анализу, а дешёвый "фильтр на входе": то, что здесь
проходит проверку — всё равно потом проходит обычный ИИ-анализ (для
категории/оператора/приоритета/резюме), а то, что явно не проходит —
отбрасывается сразу, ИИ вообще не трогается.

Специально сделан с "запасом" (лучше пропустить что-то лишнее и
ИИ его отсеет дальше, чем ошибочно выбросить настоящую жалобу по
связи) — поэтому список ключевых слов довольно широкий.
"""

# Основы слов (не полные слова) — специально без окончаний, чтобы
# одним пунктом ловить сразу все падежи/формы: "связь", "связи",
# "связью", "связался" и т.п. — все содержат основу "связ".
_TELECOM_KEYWORD_STEMS = [
    # Общие термины связи
    "связ",           # связь, связи, связью
    "интернет",
    "сеть", "сети", "сетью", "сетей",
    "wifi", "wi-fi", "вайфай", "вай-фай",
    "sim", "симк",    # симка, симку, симкой
    "тариф",
    "сотов",          # сотовый, сотовая
    "мобильн",        # мобильный, мобильной
    "роуминг",
    "модем",
    "роутер",
    "звонк",          # звонок, звонки
    "дозвон",         # дозвониться, дозвонился
    "смс", "sms",
    "абонент",
    "вышк",           # вышка, вышки (вышка связи)
    "покрыти",        # покрытие (сети)
    "баланс",         # баланс на телефоне
    "3g", "4g", "5g", "lte", "gsm",

    # Названия операторов — самый надёжный сигнал, это узнаваемые
    # бренды, которые вряд ли упомянут в жалобе на дороги/мусор
    "kcell", "кселл",
    "beeline", "билайн",
    "tele2", "теле2", "теле 2",
    "казахтелеком", "kazakhtelecom",
    "актив", "activ",

    # Казахский язык
    "байланыс",       # связь
    "желі",           # сеть
]

_NORMALIZED_STEMS = [stem.lower() for stem in _TELECOM_KEYWORD_STEMS]


def is_telecom_related(text: str) -> bool:
    """
    True, если в тексте встречается хотя бы одно из ключевых слов
    по теме связи/интернета (без учёта регистра). Не гарантирует,
    что сообщение ТОЧНО про связь (это делает уже ИИ-анализ дальше)
    — только отсеивает то, что почти наверняка НЕ про связь вообще.
    """

    if not text:
        return False

    normalized = text.lower()

    return any(
        stem in normalized
        for stem in _NORMALIZED_STEMS
    )
