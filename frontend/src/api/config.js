// Раньше здесь было жёстко "http://127.0.0.1:8000" — работало только
// если открывать сайт с того же компьютера, где запущен backend.
// Теперь по умолчанию адрес API вычисляется от того, с какого хоста
// открыт сам сайт — значит, если зайти на сайт по адресу локальной
// сети (например, http://192.168.1.50:5173), запросы к API сами
// пойдут на http://192.168.1.50:8000, без ручной правки под каждый
// компьютер.
//
// Но если фронтенд и backend оказываются на РАЗНЫХ адресах (не
// "тот же хост, другой порт") — например, при показе через туннель
// (ngrok и т.п.), где у каждого порта свой отдельный публичный
// адрес — этого автоматического вычисления недостаточно. Тогда
// адрес API можно явно задать при сборке через переменную
// VITE_API_URL (см. frontend/Dockerfile) — она имеет приоритет.
export const API_URL =
    import.meta.env.VITE_API_URL ||
    `http://${window.location.hostname}:8000`
